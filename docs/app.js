function syncTourControls(index) {
  activeStepIndex = index;
  if (currentStepLabel) currentStepLabel.textContent = String(index + 1).padStart(2, "0");
  if (previousStepButton) previousStepButton.disabled = index === 0;
  if (nextStepButton) nextStepButton.disabled = index === steps.length - 1;
}

function goToStep(index) {
  const target = steps[index];
  if (!target) return false;

  stepScrollLocked = true;
  accumulatedWheelDelta = 0;
  syncTourControls(index);
  target.scrollIntoView({
    behavior: window.matchMedia("(prefers-reduced-motion: reduce)").matches ? "auto" : "smooth",
    block: "center"
  });

  window.clearTimeout(unlockStepTimer);
  unlockStepTimer = window.setTimeout(() => { stepScrollLocked = false; }, 860);
  return true;
}

function setCursorPosition(x, y, tilt = -5) {
  cursorPosition = { x, y };
  demo?.style.setProperty("--cursor-x", x.toFixed(3));
  demo?.style.setProperty("--cursor-y", y.toFixed(3));
  demo?.style.setProperty("--cursor-tilt", tilt.toFixed(3));
}

function scheduleCursorClick(state, duration) {
  window.clearTimeout(cursorClickTimer);
  window.clearTimeout(cursorReleaseTimer);
  cursor?.classList.remove("clicking", "right-clicking");
  if (!cursor || !["panelplay", "ambient"].includes(state)) return;

  cursorClickTimer = window.setTimeout(() => {
    cursor.classList.add(state === "ambient" ? "right-clicking" : "clicking");
    cursorReleaseTimer = window.setTimeout(() => {
      cursor.classList.remove("clicking", "right-clicking");
    }, 210);
  }, duration + 90);
}

function moveScriptedCursor(step, index, state) {
  if (!demo || !cursor) return;
  window.cancelAnimationFrame(cursorFrame);
  window.clearTimeout(cursorClickTimer);
  window.clearTimeout(cursorReleaseTimer);
  window.clearTimeout(cursorPauseTimer);
  cursor.classList.remove("clicking", "right-clicking");

  const [authoredStartX, authoredStartY, targetX, targetY] = parsePoints(step);
  const targets = state === "resume"
    ? [{ x: authoredStartX, y: authoredStartY }, { x: targetX, y: targetY }]
    : [{ x: targetX, y: targetY }];
  const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  const legDuration = (from, to) => reducedMotion
    ? 0
    : clamp(480 + Math.hypot(to.x - from.x, to.y - from.y) * 4.2, 540, 820);
  let durationCursor = { ...cursorPosition };
  const durations = targets.map((target) => {
    const duration = legDuration(durationCursor, target);
    durationCursor = target;
    return duration;
  });
  const pauseBetweenLegs = targets.length > 1 ? 120 : 0;
  const totalDuration = durations.reduce((total, duration) => total + duration, 0) + pauseBetweenLegs;

  if (reducedMotion) {
    interactionProgress = 1;
    setCursorPosition(targetX, targetY);
    scheduleCursorClick(state, 0);
    return;
  }

  interactionProgress = 0;
  demo.dataset.cursorMotion = "moving";
  demo.dataset.cursorTarget = state;

  const runLeg = (legIndex) => {
    const start = { ...cursorPosition };
    const target = targets[legIndex];
    const dx = target.x - start.x;
    const dy = target.y - start.y;
    const distance = Math.max(Math.hypot(dx, dy), .001);
    const duration = durations[legIndex];
    const normalX = -dy / distance;
    const normalY = dx / distance;
    const bendDirection = (index + legIndex) % 2 === 0 ? 1 : -1;
    const bend = clamp(distance * .11, 2.2, 7.4) * bendDirection;
    const overshoot = clamp(distance * .018, .35, 1.15);
    const controlOne = {
      x: start.x + dx * .30 + normalX * bend,
      y: start.y + dy * .30 + normalY * bend
    };
    const controlTwo = {
      x: target.x + (dx / distance) * overshoot - normalX * bend * .18,
      y: target.y + (dy / distance) * overshoot - normalY * bend * .18
    };
    const startingTilt = clamp(-5 + normalX * 3, -8, -2);
    const targetTilt = clamp(-5 - normalX * 1.5, -7, -3);
    const startedAt = performance.now();
    const finalLeg = legIndex === targets.length - 1;

    const drawFrame = (now) => {
      const linearProgress = clamp((now - startedAt) / duration);
      const progress = minimumJerk(linearProgress);
      const inverse = 1 - progress;
      const x = inverse ** 3 * start.x
        + 3 * inverse ** 2 * progress * controlOne.x
        + 3 * inverse * progress ** 2 * controlTwo.x
        + progress ** 3 * target.x;
      const y = inverse ** 3 * start.y
        + 3 * inverse ** 2 * progress * controlOne.y
        + 3 * inverse * progress ** 2 * controlTwo.y
        + progress ** 3 * target.y;
      const tilt = mix(startingTilt, targetTilt, minimumJerk(clamp(linearProgress * 1.08)));

      setCursorPosition(x, y, tilt);
      interactionProgress = finalLeg ? minimumJerk(clamp((linearProgress - .68) / .32)) : 0;
      requestTourUpdate();

      if (linearProgress < 1) {
        cursorFrame = window.requestAnimationFrame(drawFrame);
        return;
      }

      setCursorPosition(target.x, target.y, targetTilt);
      if (!finalLeg) {
        cursorPauseTimer = window.setTimeout(() => runLeg(legIndex + 1), pauseBetweenLegs);
        return;
      }

      interactionProgress = 1;
      demo.dataset.cursorMotion = "settled";
      requestTourUpdate();
    };

    cursorFrame = window.requestAnimationFrame(drawFrame);
  };

  runLeg(0);
  scheduleCursorClick(state, totalDuration);
}

function setTrack(title, artist, playing = true) {
  [statusTitle, panelTrack, ambientTrack, notificationTitle].forEach((node) => { if (node) node.textContent = title; });
  [panelArtist, ambientArtist].forEach((node) => { if (node) node.textContent = artist; });
  if (notificationArtist) notificationArtist.textContent = `${artist} · Songleton Session`;
  const icon = playing ? "Ⅱ" : "▶";
  [statusPlay, panelPlay, ambientPlay].forEach((node) => { if (node) node.textContent = icon; });
}

function updateTour() {
  rafPending = false;
  if (!demo || !steps.length) return;
  const anchor = window.innerHeight * .56;
  let active = steps[0];
  for (const step of steps) {
    const rect = step.getBoundingClientRect();
    if (rect.top <= anchor) active = step;
    if (rect.top <= anchor && rect.bottom > anchor) { active = step; break; }
  }

  const rect = active.getBoundingClientRect();
  const activeIndex = steps.indexOf(active);
  syncTourControls(activeIndex);
  const rawProgress = clamp((anchor - rect.top) / Math.max(rect.height * .72, 1));
  demo.style.setProperty("--step-progress", rawProgress.toFixed(3));

  const state = active.dataset.state;
  if (activeState !== state) {
    activeState = state;
    demo.dataset.state = state;
    demo.classList.remove("beat");
    lastBeat = -1;
    moveScriptedCursor(active, activeIndex, state);
  }
  steps.forEach((step) => step.classList.toggle("active", step === active));

  const panelOpacity = state === "hover"
    ? clamp(rawProgress * 2.4) * interactionProgress
    : state === "panelplay"
      ? 1
      : state === "ambient"
        ? clamp(1 - Math.max(0, rawProgress - .42) * 3) * interactionProgress
        : 0;
  const ambientOpacity = state === "ambient" ? clamp((rawProgress - .43) * 3.2) * interactionProgress : state === "lyrics" ? interactionProgress : 0;
  const edgeOpacity = ["previous", "next", "pause", "resume"].includes(state) ? clamp(rawProgress * 3) * interactionProgress : 0;
  const volumeOpacity = state === "volume" ? clamp(rawProgress * 3) * interactionProgress : 0;
  const noticeOpacity = state === "notification" ? clamp((rawProgress - .18) * 3.1) * interactionProgress : 0;
  const settingsOpacity = state === "settings" ? clamp((rawProgress - .1) * 2.5) * interactionProgress : 0;
  demo.style.setProperty("--panel-opacity", panelOpacity.toFixed(3));
  demo.style.setProperty("--ambient-opacity", ambientOpacity.toFixed(3));
  demo.style.setProperty("--edge-opacity", edgeOpacity.toFixed(3));
  demo.style.setProperty("--volume-opacity", volumeOpacity.toFixed(3));
  demo.style.setProperty("--notice-opacity", noticeOpacity.toFixed(3));
  demo.style.setProperty("--settings-opacity", settingsOpacity.toFixed(3));

  if (state === "previous" && interactionProgress > .62) setTrack("After Dark", "Mr.Kitty");
  else if (state === "next" && interactionProgress > .62) setTrack("Midnight City", "M83");
  else if (state === "pause" && interactionProgress > .62) setTrack("Midnight City", "M83", false);
  else if (state === "resume") {
    setTrack("Midnight City", "M83", interactionProgress > .62);
    const beat = Math.floor(Math.max(0, interactionProgress - .62) * 8);
    if (interactionProgress > .62 && beat !== lastBeat) {
      lastBeat = beat;
      demo.classList.remove("beat");
      void demo.offsetWidth;
      demo.classList.add("beat");
    }
  } else if (!["previous", "pause"].includes(state)) setTrack("Midnight City", "M83");

  if (state === "lyrics") {
    const theme = rawProgress < .34 ? "vinyl" : rawProgress < .68 ? "cassette" : "glass";
    demo.dataset.theme = theme;
    if (ambientModeName) ambientModeName.textContent = `AMBIENT · ${theme.toUpperCase()}`;
  } else {
    demo.dataset.theme = "vinyl";
    if (ambientModeName) ambientModeName.textContent = "AMBIENT · VINYL";
  }
}

function requestTourUpdate() {
  if (rafPending) return;
  rafPending = true;
  requestAnimationFrame(updateTour);
}

window.addEventListener("scroll", requestTourUpdate, { passive: true });
window.addEventListener("resize", requestTourUpdate);

const scrollProgressBar = document.querySelector(".scroll-progress");
function updateScrollProgress() {
  if (!scrollProgressBar) return;
  const max = document.documentElement.scrollHeight - window.innerHeight;
  const progress = max > 0 ? window.scrollY / max : 0;
  scrollProgressBar.style.width = `${Math.min(1, progress) * 100}%`;
}
