function applyLanguage(language) {
  const selected = copy[language] ? language : "tr";
  document.documentElement.lang = selected;
  document.title = copy[selected].pageTitle;
  document.querySelector('meta[name="description"]')?.setAttribute("content", copy[selected].pageDescription);
  document.querySelectorAll("[data-i18n-label]").forEach((node) => {
    const value = copy[selected][node.dataset.i18nLabel];
    if (value !== undefined) node.setAttribute("aria-label", value);
  });
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const value = copy[selected][node.dataset.i18n];
    if (value === undefined) return;
    if (node.dataset.i18n === "heroTitle" || node.dataset.i18n === "ctaTitle") {
      const parts = value.split("<br>");
      const accent = document.createElement("span");
      accent.textContent = (parts[1] || "").replace(/^<span>|<\/span>$/g, "");
      node.replaceChildren(document.createTextNode(parts[0]), document.createElement("br"), accent);
    } else node.textContent = value;
  });
  document.querySelectorAll("[data-language]").forEach((button) => button.setAttribute("aria-pressed", String(button.dataset.language === selected)));
  if (menuLanguage) menuLanguage.textContent = selected.toUpperCase();
  if (menuClock) menuClock.textContent = selected === "tr" ? "Çar 01:18" : "Wed 01:18";
  try { localStorage.setItem("songleton-language", selected); } catch (_) {}
}

