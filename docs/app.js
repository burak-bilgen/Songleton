const clamp = (value, min = 0, max = 1) => Math.min(max, Math.max(min, value));
const mix = (from, to, progress) => from + (to - from) * progress;
const parsePoints = (step) => step.dataset.cursor.split(",").map(Number);
const minimumJerk = (value) => value ** 3 * (10 + value * (-15 + value * 6));
